//! The vendored API specification, embedded at compile time.
//!
//! `spec/api-signatures.json` is generated from the upstream documentation by
//! `spec/tools/extract_signatures.py`. Embedding it means the shipped binary
//! carries its own contract: [`spec::signatures`] is what the coverage test
//! compares the implementation against, and [`spec::summary`] is what
//! `--selftest` prints.
//!
//! Nothing here is hand-maintained, so the spec cannot drift away from the
//! documentation without the extraction tool being re-run — and if it is re-run
//! with a different result, the coverage test fails until the implementation
//! catches up.

use std::sync::OnceLock;

use serde::Deserialize;

/// Raw JSON of every documented signature.
const SIGNATURES_JSON: &str = include_str!("../../../spec/api-signatures.json");

/// One documented function.
#[derive(Clone, Debug, Deserialize)]
pub struct Signature {
    /// Owning service, e.g. `CurrencyService`.
    pub service: String,
    /// Method name; empty when the service itself is callable.
    pub method: String,
    /// Documented parameter names, in order.
    pub params: Vec<String>,
    /// Whether the signature takes a trailing `...`.
    pub varargs: bool,
    /// The documentation section it came from.
    #[serde(default)]
    pub source_section: String,
    /// The original line, kept for error messages.
    #[serde(default)]
    pub raw: String,
    /// Number of named parameters.
    #[serde(default)]
    pub arity: usize,
}

impl Signature {
    /// The `Service.Method` key, or just `Service` for a callable service.
    pub fn key(&self) -> String {
        if self.method.is_empty() {
            self.service.clone()
        } else {
            format!("{}.{}", self.service, self.method)
        }
    }
}

/// The whole specification document.
#[derive(Clone, Debug, Deserialize)]
pub struct Spec {
    /// Where the documentation lives.
    pub source: String,
    /// The published documentation URL.
    pub upstream: String,
    /// Number of signatures.
    pub signature_count: usize,
    /// Number of services.
    pub service_count: usize,
    /// Every service name.
    pub services: Vec<String>,
    /// Every signature.
    pub signatures: Vec<Signature>,
}

fn parsed() -> &'static Spec {
    static SPEC: OnceLock<Spec> = OnceLock::new();
    SPEC.get_or_init(|| {
        serde_json::from_str(SIGNATURES_JSON).expect(
            "spec/api-signatures.json is generated by spec/tools/extract_signatures.py and must be valid",
        )
    })
}

/// The specification, parsed once.
pub fn spec() -> &'static Spec {
    parsed()
}

/// Every documented signature.
pub fn signatures() -> &'static [Signature] {
    &spec().signatures
}

/// The documented service names, sorted.
pub fn services() -> &'static [String] {
    &spec().services
}

/// The signature for a `Service.Method` key, if documented.
pub fn find(service: &str, method: &str) -> Option<&'static Signature> {
    signatures()
        .iter()
        .find(|s| s.service == service && s.method == method)
}

/// The documented methods of one service.
pub fn methods_of(service: &str) -> Vec<&'static str> {
    signatures()
        .iter()
        .filter(|s| s.service == service)
        .map(|s| s.method.as_str())
        .collect()
}

/// A one-line summary for logs and `--selftest`.
pub fn summary() -> String {
    let spec = spec();
    format!(
        "{} documented functions across {} services ({})",
        spec.signature_count, spec.service_count, spec.upstream
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spec_is_embedded_and_consistent() {
        let spec = spec();
        assert_eq!(
            spec.signatures.len(),
            spec.signature_count,
            "signature_count must match the array length"
        );
        assert_eq!(spec.services.len(), spec.service_count);
        assert!(spec.upstream.contains("noobietoria.github.io"));
        assert!(spec.source.contains("api.md"));
    }

    #[test]
    fn every_signature_is_well_formed() {
        for s in signatures() {
            assert!(!s.service.is_empty(), "service name is empty: {:?}", s.raw);
            assert!(
                s.service
                    .chars()
                    .next()
                    .is_some_and(|c| c.is_ascii_uppercase()),
                "service `{}` should be capitalised",
                s.service
            );
            assert_eq!(
                s.arity,
                s.params.len(),
                "arity disagrees with params for {}",
                s.key()
            );
            assert!(!s.raw.is_empty(), "{} has no source line", s.key());
        }
    }

    #[test]
    fn keys_are_unique() {
        let mut keys: Vec<String> = signatures().iter().map(Signature::key).collect();
        let total = keys.len();
        keys.sort();
        keys.dedup();
        assert_eq!(keys.len(), total, "duplicate signature key in the spec");
    }

    #[test]
    fn services_list_matches_the_signatures() {
        let mut from_signatures: Vec<String> =
            signatures().iter().map(|s| s.service.clone()).collect();
        from_signatures.sort();
        from_signatures.dedup();
        assert_eq!(from_signatures, services().to_vec());
    }

    #[test]
    fn known_signatures_are_present() {
        // Spot checks against the documentation text.
        let s = find("CurrencyService", "Add").expect("CurrencyService.Add is documented");
        assert_eq!(s.params, vec!["Username", "CurrencyType", "Amount"]);
        assert_eq!(s.arity, 3);

        let s = find("UIService", "Create").expect("UIService.Create is documented");
        assert_eq!(s.params, vec!["Name", "Type", "Parent", "Properties"]);

        let s = find("NetworkService", "FireClient").expect("FireClient is documented");
        assert_eq!(s.params, vec!["Name", "Username", "Index"]);
        assert!(s.varargs, "FireClient takes a trailing `...`");

        let s = find("TweenService", "Move").expect("TweenService.Move is documented");
        assert_eq!(s.arity, 7);
    }

    #[test]
    fn coverage_target_is_reported() {
        // The number the coverage test must match. Kept explicit so a change in
        // the vendored docs is noticed here first.
        assert_eq!(spec().signature_count, 366);
        assert_eq!(spec().service_count, 45);
        assert!(summary().contains("366"));
    }

    #[test]
    fn methods_of_lists_a_service() {
        let methods = methods_of("BanService");
        assert!(methods.contains(&"Ban"));
        assert!(methods.contains(&"Kick"));
        assert!(methods.contains(&"GetBanHistory"));
        assert!(methods_of("NotAService").is_empty());
    }
}
